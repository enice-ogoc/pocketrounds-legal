def install_block(testflight_url: str = TESTFLIGHT_PUBLIC_URL, app_store_url: str = APP_STORE_URL) -> str:
    """Button area under Open PocketRounds.

    An App Store URL replaces the testing sentence with the App Store button
    and the after-install sentence. A TestFlight URL adds a link only while
    the testing sentence is showing. Empty strings render neither link.
    """
    store = app_store_url.strip()
    if store:
        href = html.escape(store, quote=True)
        return (
            f'<a class="store" href="{href}">App Store</a>\n'
            f'    <p class="after">{html.escape(AFTER_INSTALL)}</p>'
        )
    block = f'<p class="testing">{html.escape(TESTING)}</p>'
    flight = testflight_url.strip()
    if flight:
        href = html.escape(flight, quote=True)
        block += f'\n    <p class="tf"><a href="{href}">Join on TestFlight</a></p>'
    return block


def render(page: dict) -> str:
    label = page["label"]
    label_html = (
        f'<p class="label">{html.escape(label)}</p>' if label else ""
    )
    replacements = {
        "__TITLE__": html.escape(page["title"], quote=True),
        "__DESCRIPTION__": html.escape(DESCRIPTION, quote=True),
        "__URL__": html.escape(page_url(page), quote=True),
        "__IMAGE__": html.escape(image_url(page), quote=True),
        "__ALT__": html.escape(page["alt"], quote=True),
        "__LABEL__": label_html,
        "__FALLBACK__": html.escape(FALLBACK),
        "__INSTALL__": install_block(TESTFLIGHT_PUBLIC_URL, APP_STORE_URL),
        "__SUPPORT__": html.escape(support_url(), quote=True),
    }
    text = TEMPLATE
    for token, value in replacements.items():
        text = text.replace(token, value)
    if "__" in text:
        raise SystemExit("unreplaced template token in " + page["path"])
    return text


def output_path(root: Path, page: dict) -> Path:
    return root / page["path"].strip("/") / "index.html"


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    for page in PAGES:
        dest = output_path(root, page)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(render(page), encoding="utf-8", newline="\n")
        print(dest.relative_to(root).as_posix())


if __name__ == "__main__":
    main()
